package protogen

import (
	"strconv"
	"strings"

	"github.com/pkg/errors"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

// ESTypeIDPluginName is the TypeScript typeid generator served in process.
const ESTypeIDPluginName = "protoc-gen-es-typeid"

// esTypedMessage is a message that declares a (typeid.id) option, named as
// protoc-gen-es-lite exports it.
type esTypedMessage struct {
	// name is the exported identifier of the generated message.
	name string
	// id is the declared type identifier.
	id string
}

// GenerateESTypeIDs answers one encoded CodeGeneratorRequest for the
// TypeScript typeid generator. For each proto file with typed messages it
// emits <name>_typeid.pb.ts beside protoc-gen-es-lite's <name>.pb.ts, holding
// a TypeID constant per message and the file's list of identifiers and
// message types.
func GenerateESTypeIDs(input []byte) ([]byte, error) {
	// Decode the request and resolve its descriptors.
	req := &pluginpb.CodeGeneratorRequest{}
	if err := proto.Unmarshal(input, req); err != nil {
		return nil, err
	}
	files, err := protodesc.NewFiles(&descriptorpb.FileDescriptorSet{File: req.GetProtoFile()})
	if err != nil {
		return nil, err
	}
	resp := &pluginpb.CodeGeneratorResponse{
		SupportedFeatures: proto.Uint64(uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL |
			pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)),
		MinimumEdition: proto.Int32(int32(descriptorpb.Edition_EDITION_PROTO2)),
		MaximumEdition: proto.Int32(int32(descriptorpb.Edition_EDITION_2024)),
	}

	// Emit one file per requested proto that declares a type identifier.
	for _, path := range req.GetFileToGenerate() {
		file, err := files.FindFileByPath(path)
		if err != nil {
			return nil, err
		}
		types, err := esFileTypedMessages(file)
		if err != nil {
			resp.Error = proto.String(err.Error())
			resp.File = nil
			break
		}
		if len(types) != 0 {
			resp.File = append(resp.File, &pluginpb.CodeGeneratorResponse_File{
				Name:    proto.String(strings.TrimSuffix(path, ".proto") + "_typeid.pb.ts"),
				Content: proto.String(esTypeIDFile(path, types)),
			})
		}
	}

	return proto.Marshal(resp)
}

// esFileTypedMessages lists the typed messages of a file in declaration order
// and rejects an identifier declared twice.
func esFileTypedMessages(file protoreflect.FileDescriptor) ([]esTypedMessage, error) {
	// Collect the typed messages of the whole nested message tree.
	types, err := appendESTypedMessages(nil, file.Package(), file.Messages())
	if err != nil {
		return nil, err
	}

	// A type identifier names exactly one message.
	seen := make(map[string]string, len(types))
	for _, t := range types {
		if prev, ok := seen[t.id]; ok {
			return nil, errors.Errorf("%s: type id %q already declared by %s", t.name, t.id, prev)
		}
		seen[t.id] = t.name
	}
	return types, nil
}

// appendESTypedMessages appends each typed message of msgs and their nested
// messages, depth first in declaration order.
func appendESTypedMessages(types []esTypedMessage, pkg protoreflect.FullName, msgs protoreflect.MessageDescriptors) ([]esTypedMessage, error) {
	for i := range msgs.Len() {
		// Read the message's own option before its nested messages.
		msg := msgs.Get(i)
		id, ok, err := messageTypeID(msg)
		if err != nil {
			return nil, errors.Wrap(err, string(msg.FullName()))
		}
		if ok {
			types = append(types, esTypedMessage{name: esMessageName(pkg, msg.FullName()), id: id})
		}

		// Nested messages follow their parent.
		types, err = appendESTypedMessages(types, pkg, msg.Messages())
		if err != nil {
			return nil, err
		}
	}
	return types, nil
}

// esTypeIDFile renders the TypeID declarations and list of one file.
func esTypeIDFile(path string, types []esTypedMessage) string {
	// Import the message types from protoc-gen-es-lite's output.
	var b strings.Builder
	base := strings.TrimSuffix(baseName(path), ".proto")
	b.WriteString("// Code generated by " + ESTypeIDPluginName + ". DO NOT EDIT.\n")
	b.WriteString("// source: " + path + "\n\n")
	b.WriteString("import {\n")
	for _, t := range types {
		b.WriteString("  " + t.name + ",\n")
	}
	b.WriteString("} from './" + base + ".pb.js'\n")

	// Declare each message's identifier.
	for _, t := range types {
		b.WriteString("\n// " + t.name + "TypeID is the type ID of " + t.name + ".\n")
		b.WriteString("export const " + t.name + "TypeID = " + strconv.Quote(t.id) + "\n")
	}

	// List the file's typed messages with their message types.
	listName := typeIDListName(path)
	b.WriteString("\n// " + listName + " lists the typed messages of " + baseName(path) + ".\n")
	b.WriteString("export const " + listName + " = [\n")
	for _, t := range types {
		b.WriteString("  { id: " + t.name + "TypeID, message: " + t.name + " },\n")
	}
	b.WriteString("] as const\n")
	return b.String()
}

// esMessageName returns the identifier protoc-gen-es-lite exports for a
// message: its name below the package with nested names joined by an
// underscore, and a trailing $ on a reserved identifier.
func esMessageName(pkg, name protoreflect.FullName) string {
	// Join the nested names below the package, then escape a reserved one.
	local := string(name)
	if pkg != "" {
		local = local[len(pkg)+1:]
	}
	local = strings.ReplaceAll(local, ".", "_")
	if _, ok := esReservedIdentifiers[local]; ok {
		return local + "$"
	}
	return local
}

// esReservedIdentifiers are the names protoc-gen-es-lite escapes with $.
var esReservedIdentifiers = map[string]struct{}{
	"break": {}, "case": {}, "catch": {}, "class": {}, "const": {},
	"continue": {}, "debugger": {}, "default": {}, "delete": {}, "do": {},
	"else": {}, "export": {}, "extends": {}, "false": {}, "finally": {},
	"for": {}, "function": {}, "if": {}, "import": {}, "in": {},
	"instanceof": {}, "new": {}, "null": {}, "return": {}, "super": {},
	"switch": {}, "this": {}, "throw": {}, "true": {}, "try": {},
	"typeof": {}, "var": {}, "void": {}, "while": {}, "with": {},
	"yield": {}, "enum": {}, "implements": {}, "interface": {}, "let": {},
	"package": {}, "private": {}, "protected": {}, "public": {}, "static": {},
	"Object": {}, "bigint": {}, "number": {}, "boolean": {}, "string": {},
	"object": {}, "globalThis": {}, "Uint8Array": {}, "Partial": {},
}
