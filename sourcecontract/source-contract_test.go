func TestCheckReturnsDeterministicDiagnostics(t *testing.T) {
	root := newGitProject(t)
	writeSource(t, root, "ordered.go", `package fixture

const (alpha = 1; beta = 2)






func later() {}
`)
	writeSource(t, root, "rules.proto", `syntax = "proto3";
message Record { string value = 1; }
`)
	writeSource(t, root, "z.go", "package fixture\n\nfunc zed() {}\n")

	first := Check(root)
	second := Check(root)
	if first == nil || second == nil || first.Error() != second.Error() {
		t.Fatalf("diagnostics differ:\nfirst: %v\nsecond: %v", first, second)
	}
	records := parseDiagnosticRecords(t, first.Error())
	if len(records) < 6 {
		t.Fatalf("too few diagnostic records to exercise ordering: %v", first)
	}
	for index := 1; index < len(records); index++ {
		if diagnosticRecordLess(records[index], records[index-1]) {
			t.Fatalf("diagnostics are not path-byte/line/column/rule sorted at %q then %q", records[index-1].raw, records[index].raw)
		}
	}

	var numericLine, numericColumn, ruleTie bool
	for index := 1; index < len(records); index++ {
		previous, current := records[index-1], records[index]
		if previous.path == current.path && previous.line < current.line && current.line >= 10 {
			numericLine = true
		}
		if previous.path == current.path && previous.line == current.line && previous.column < current.column {
			numericColumn = true
		}
		if previous.path == current.path && previous.line == current.line && previous.column == current.column && previous.rule < current.rule {
			ruleTie = true
		}
	}
	if !numericLine || !numericColumn || !ruleTie {
		t.Fatalf("fixtures did not exercise numeric line, numeric column, and rule tie ordering: line=%t column=%t rule=%t\n%v", numericLine, numericColumn, ruleTie, first)
	}
}

type diagnosticRecord struct {
	raw    string
	path   string
	line   int
	column int
	rule   string
}

var diagnosticRecordPattern = regexp.MustCompile(`^([^:]+):([0-9]+):([0-9]+): ([^:]+): .+$`)

func parseDiagnosticRecords(t *testing.T, diagnostics string) []diagnosticRecord {
	t.Helper()
	var records []diagnosticRecord
	for _, line := range strings.Split(diagnostics, "\n") {
		match := diagnosticRecordPattern.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		lineNumber, err := strconv.Atoi(match[2])
		if err != nil {
			t.Fatal(err)
		}
		column, err := strconv.Atoi(match[3])
		if err != nil {
			t.Fatal(err)
		}
		records = append(records, diagnosticRecord{
			raw: line, path: match[1], line: lineNumber, column: column, rule: match[4],
		})
	}
	return records
}

func diagnosticRecordLess(left, right diagnosticRecord) bool {
	if pathOrder := bytes.Compare([]byte(left.path), []byte(right.path)); pathOrder != 0 {
		return pathOrder < 0
	}
	if left.line != right.line {
		return left.line < right.line
	}
	if left.column != right.column {
		return left.column < right.column
	}
	return left.rule < right.rule
}

func newGitProject(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	runGit(t, root, "init", "--quiet")
	return root
}

func writeSource(t *testing.T, root, name, source string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
}

func runGit(t *testing.T, root string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = root
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, output)
	}
}

func assertDiagnostics(t *testing.T, err error, wants ...string) {
	t.Helper()
	if err == nil {
		t.Fatalf("Check() succeeded, want diagnostics containing %v", wants)
	}
	for _, want := range wants {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("Check() error does not contain %q: %v", want, err)
		}
	}
}

func assertNoDiagnostics(t *testing.T, err error, rejects ...string) {
	t.Helper()
	if err == nil {
		return
	}
	for _, reject := range rejects {
		if strings.Contains(err.Error(), reject) {
			t.Errorf("Check() error unexpectedly contains %q: %v", reject, err)
		}
	}
}

func generatedGo(markerLine int) string {
	lines := make([]string, markerLine-1)
	for index := range lines {
		lines[index] = "// preamble"
	}
	lines = append(lines, "// Code generated by fixture. DO NOT EDIT.", "package fixture", "", "func generated() {}")
	return strings.Join(lines, "\n") + "\n"
}

func invalidProto(name string) string {
	return "syntax = \"proto3\";\nmessage " + name + " {}\n"
}
