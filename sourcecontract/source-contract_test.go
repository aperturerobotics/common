func TestCheckRejectsProtobufLayoutAndZeroValueViolations(t *testing.T) {
	tests := map[string]string{
		"one-line-message": `// Record contains a value.
message Record { string value = 1; }`,
		"one-line-enum": `// State describes state.
enum State { STATE_UNKNOWN = 0; }`,
		"members-share-line": `// Record contains values.
message Record {
  // First identifies the first value.
  string first = 1; string second = 2;
}`,
		"rpc-shares-line": `// Records serves records.
service Records { // Read reads a record.
  rpc Read(Record) returns (Record); rpc Write(Record) returns (Record);
}`,
		"missing-separation": `// First contains a value.
message First {
}
// Second contains a value.
message Second {
}`,
		"excess-separation": `// First contains a value.
message First {
}


// Second contains a value.
message Second {
}`,
		"wrong-zero": `// State describes state.
enum State {
  // STATE_UNSPECIFIED is the default state.
  STATE_UNSPECIFIED = 0;
}`,
	}
	for name, source := range tests {
		t.Run(name, func(t *testing.T) {
			root := newGitProject(t)
			writeSource(t, root, "layout.proto", "syntax = \"proto3\";\n\n"+source+"\n")
			if err := Check(root); err == nil {
				t.Fatal("Check() unexpectedly accepted invalid protobuf layout")
			}
		})
	}
}

